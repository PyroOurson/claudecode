const lib = require('../lib.js');
const { execFileSync } = require('child_process');
const DBC = process.env.STAGE_DB || 'supabase_db_staging';
const sql = q => execFileSync('docker', ['exec', '-i', DBC, 'psql', '-U', 'postgres', '-d', 'postgres', '-Atqc', q]).toString().trim();
const sleep = ms => new Promise(r => setTimeout(r, ms));
const GAME = process.env.PARTY_GAME || 'last-card';
const noPeerJs = async v => { await v.ctx.route(/peerjs\.com/, r => r.abort()); await v.ctx.routeWebSocket(/peerjs\.com/, ws => ws.close()); };
const hostParty = async h => { await h.toParty(GAME); await h.click('gohost'); await h.click('mkpriv'); await h.waitLobby(1); return (await h.lobby()).code; };
const joinCode = async (g, code) => { await g.toParty(GAME); await g.click('gojoin'); await g.page.fill('.g-lobby .gl-code-in', code); await g.tap('.g-lobby .gl-jbtn'); };
(async () => {
  const id = u => sql("select id from public.profiles where username = '" + u + "'");
  const ann = id('ann_player'), bob = id('bob_player'), stranger = id('load_player1');
  const c = lib.api.conf();
  const b = await lib.launch();
  const out = [], fail = [];
  const must = (ok, m) => { (ok ? out : fail).push(m); };
  try {
    const a = await lib.player(b, 'ann');
    const r = await a.page.evaluate(async ([url, key, ann, bob, stranger]) => {
      const lib = window.supabase;
      const raw = JSON.parse(localStorage.getItem('sb-gameplay-auth') || 'null');
      const cl = lib.createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
      await cl.auth.setSession({ access_token: raw.access_token, refresh_token: raw.refresh_token });
      cl.realtime.setAuth(raw.access_token);
      const join = topic => new Promise(res => { const ch = cl.channel(topic, { config: { private: true } }); const t = setTimeout(() => { res('timeout'); cl.removeChannel(ch); }, 8000); ch.subscribe(s => { if (s === 'SUBSCRIBED' || s === 'CHANNEL_ERROR') { clearTimeout(t); res(s); cl.removeChannel(ch); } }); });
      const send = async topic => { const ch = cl.channel(topic, { config: { private: true } }); try { const x = await ch.httpSend('n', { t: 'probe' }); return x && x.success === false ? 'refused' : 'sent'; } catch (e) { return 'refused'; } finally { cl.removeChannel(ch); } };
      return { own: await join('u:' + ann), other: await join('u:' + bob), site: await join('site'), party: await join('gp:last-card:ABCD'), junk: await join('x:foo'), friend: await send('u:' + bob), notFriend: await send('u:' + stranger), siteSend: await send('site') };
    }, [c.url, c.key, ann, bob, stranger]);
    must(r.own === 'SUBSCRIBED', 'a player can join their own channel (' + r.own + ')');
    must(r.other === 'CHANNEL_ERROR', 'a player cannot listen to another player’s channel (' + r.other + ')');
    must(r.site === 'SUBSCRIBED' && r.siteSend === 'refused', 'players can listen to the site channel but not send to it (' + r.site + ', ' + r.siteSend + ')');
    must(r.party === 'SUBSCRIBED', 'party doors can be joined (' + r.party + ')');
    must(r.junk === 'CHANNEL_ERROR', 'unknown channels are refused (' + r.junk + ')');
    must(r.friend === 'sent' && r.notFriend === 'refused', 'nudges go to friends only (' + r.friend + ', ' + r.notFriend + ')');
    await a.close();
    const h = await lib.player(b, 'test');
    const code = await hostParty(h);
    await sleep(3000);
    const real = sql("select door_key from private.parties where game = '" + GAME + "' and code = '" + code + "'");
    must(!!real, 'the host registered its door key');
    sql("update private.parties set door_key = 'Zm9yZ2VkLWtleS1mb3ItdGhlLXRlc3Q' where game = '" + GAME + "' and code = '" + code + "'");
    const g = await lib.player(b, 'test2', { setup: noPeerJs });
    await joinCode(g, code);
    await sleep(14000);
    const ev = (await g.net()).map(e => e.a);
    const joined = await g.page.evaluate(() => { const l = document.querySelector('.g-lobby .gl-lob'); return !!l && l.querySelectorAll('.gl-players .gl-pl:not(.gl-seat)').length >= 2; });
    must(!joined && ev.indexOf('rt-key-mismatch') >= 0, 'a guest refuses a party whose door key does not match the registry (joined: ' + joined + ', mismatch seen: ' + (ev.indexOf('rt-key-mismatch') >= 0) + ')');
    await g.close();
    sql("update private.parties set door_key = '" + real + "' where game = '" + GAME + "' and code = '" + code + "'");
    const g2 = await lib.player(b, 'test2', { setup: noPeerJs });
    await joinCode(g2, code);
    await g2.waitLobby(2, 60000);
    const ev2 = (await g2.net()).filter(e => e.a === 'rt-verify').map(e => e.key);
    must(ev2.indexOf(true) >= 0, 'with the right key the guest joins through the second route and reports it verified');
    await g2.close(); await h.close();
  } catch (e) { fail.push('error: ' + String(e && e.message || e).split('\n')[0]); }
  await b.close();
  out.forEach(m => console.log('PASS ' + m));
  fail.forEach(m => console.log('FAIL ' + m));
  console.log(fail.length ? fail.length + ' failing' : 'all passing');
  process.exit(fail.length ? 1 : 0);
})();
