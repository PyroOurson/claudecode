const lib = require('../lib.js');
const { execFileSync } = require('child_process');
const DBC = process.env.STAGE_DB || 'supabase_db_staging';
const sql = q => execFileSync('docker', ['exec', '-i', DBC, 'psql', '-U', 'postgres', '-d', 'postgres', '-Atqc', q]).toString().trim();
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const c = lib.api.conf();
  const origin = new URL(lib.BASE).origin;
  const fn = body => fetch(c.url + '/functions/v1/login', { method: 'POST', headers: { apikey: c.key, 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(body) }).then(async r => ({ status: r.status, j: await r.json().catch(() => null) }));
  sql("delete from private.analytics_rate where k like 'lg:%' or k like 'lgi:%'");
  const out = [], fail = [];
  const must = (ok, m) => { (ok ? out : fail).push(m); };
  const b = await lib.launch();
  try {
    const okr = await fn({ login: 'bob_player', password: 'Passw0rd123' });
    must(okr.status === 200 && okr.j && okr.j.session && okr.j.session.access_token, 'the sign-in function returns a session for a right username and password (' + okr.status + ')');
    must(!JSON.stringify(okr.j || {}).includes('@example.com'), 'the answer never contains the email address');
    const bad = await fn({ login: 'bob_player', password: 'wrong-password-1' });
    const none = await fn({ login: 'nobody_here_xyz', password: 'wrong-password-1' });
    must(bad.status === 400 && none.status === 400 && bad.j.error === none.j.error, 'a wrong password and an unknown username get the same answer (' + bad.j.error + ')');
    const old = await lib.api.call('/rest/v1/rpc/login_email', { body: { p_login: 'bob_player', p_password: 'Passw0rd123' } });
    must(old === null, 'the old database password check no longer answers');
    let lim = null;
    for (let i = 0; i < 8; i++) { const r = await fn({ login: 'cat_player', password: 'wrong-' + i }); if (r.status === 429) { lim = i + 1; break; } }
    must(lim && lim <= 8, 'repeated wrong passwords for one username are stopped (after ' + lim + ' tries)');
    sql("delete from private.analytics_rate where k like 'lg:%' or k like 'lgi:%'");
    const v = await lib.visitor(b);
    await v.goto('', 500);
    await v.login('bob_player', 'Passw0rd123');
    must(await v.signedIn(), 'signing in with a username in the site works');
    await v.page.evaluate(() => { const e = document.querySelector('[data-go="msettings"]'); if (e) e.click(); });
    await sleep(800);
    await v.page.evaluate(() => { const e = document.querySelector('[data-p="account"]'); if (e) e.click(); });
    await v.page.waitForSelector('#aupw2', { state: 'visible', timeout: 30000 });
    const cur = await v.page.evaluate(() => { const f = document.querySelector('#aucurf'); return !!f && !f.hidden; });
    must(cur, 'settings show a current password field for an account with a password');
    await v.page.fill('#aupw2', 'Passw0rd456');
    await v.page.click('#aupwsave');
    await sleep(1500);
    const n1 = await v.page.evaluate(() => document.querySelector('#aupwnote').textContent);
    must(/current password first/i.test(n1), 'changing the password without the current one is refused: ' + n1);
    await v.page.fill('#aucur', 'not-my-password');
    await v.page.fill('#aupw2', 'Passw0rd456');
    await v.page.click('#aupwsave');
    await sleep(2500);
    const n2 = await v.page.evaluate(() => document.querySelector('#aupwnote').textContent);
    must(/not right/i.test(n2), 'a wrong current password is refused: ' + n2);
    await v.page.fill('#aucur', 'Passw0rd123');
    await v.page.fill('#aupw2', 'Passw0rd456');
    await v.page.click('#aupwsave');
    await sleep(3000);
    const n3 = await v.page.evaluate(() => document.querySelector('#aupwnote').textContent);
    must(/saved/i.test(n3), 'with the right current password the change is saved: ' + n3);
    await v.page.fill('#aucur', 'Passw0rd456');
    await v.page.fill('#aupw2', 'Passw0rd123');
    await v.page.click('#aupwsave');
    await sleep(3000);
    await v.close();
  } catch (e) { fail.push('error: ' + String(e && e.message || e).split('\n')[0]); }
  await b.close();
  out.forEach(m => console.log('PASS ' + m));
  fail.forEach(m => console.log('FAIL ' + m));
  console.log(fail.length ? fail.length + ' failing' : 'all passing');
  process.exit(fail.length ? 1 : 0);
})();
