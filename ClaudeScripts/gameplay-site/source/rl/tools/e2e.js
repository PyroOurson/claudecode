const { launch } = require('/tmp/gameplay-build/t/lib.js');
const [html, outDir, w, h] = process.argv.slice(2);
const fs = require('fs');
fs.mkdirSync(outDir, { recursive: true });
(async () => {
  const { b, ctx } = await launch({ viewport: { width: +w || 1280, height: +h || 720 } });
  await ctx.addInitScript(() => { try { localStorage.setItem('gameplay:v1', JSON.stringify({ best: {}, plays: {}, recent: [], muted: true, theater: false })); } catch (e) {} });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push('PAGEERR ' + e.message.slice(0, 400)));
  p.on('console', m => { if (m.type() === 'error' && !/Failed to load/.test(m.text())) errs.push('ERR ' + m.text().slice(0, 400)); });
  await p.goto('file://' + html + '#/rocket-soccer');
  await p.waitForTimeout(2500);
  const box = async () => p.evaluate(() => { const r = document.querySelector('#frame .g-root .wrap').getBoundingClientRect(); return { x: r.left, y: r.top, width: r.width, height: r.height }; });
  const shot = async n => { const bx = await box(); await p.screenshot({ path: outDir + '/' + n + '.png', clip: bx }); };
  const ev = s => p.evaluate(s).catch(e => errs.push('EVAL ' + e.message.slice(0, 200)));
  const log = [];
  await p.waitForTimeout(1500);
  await shot('01_menu');
  await ev(`(() => { const m = document.querySelector('.menu'); const b = m.querySelector('[data-k="size"][data-v="3"]'); if (b) b.click(); else { const x = document.createElement('button'); x.dataset.k = 'size'; x.dataset.v = '3'; m.querySelector('.mp').append(x); x.click(); } })()`);
  await p.waitForTimeout(400);
  await shot('02_menu3');
  await ev(`document.querySelector('.menu [data-go]').click()`);
  await p.waitForTimeout(1500);
  await shot('03_countdown');
  await p.waitForFunction(() => document.querySelector('.wrap').__rs.world().state === 'play', null, { timeout: 180000 }).catch(() => errs.push('never reached play'));
  await p.keyboard.down('KeyW'); await p.keyboard.down('ShiftLeft');
  await p.waitForTimeout(1800);
  await shot('04_drive');
  await p.keyboard.up('ShiftLeft');
  await p.keyboard.press('Space');
  await p.waitForTimeout(300);
  await shot('05_jump');
  await p.keyboard.up('KeyW');
  const st = await p.evaluate(() => { const W = document.querySelector('.wrap').__rs.world(); return { n: W.cars.length, bodies: W.cars.map(c => c.body + ':' + c.name), state: W.state }; });
  log.push(JSON.stringify(st));
  await ev(`(() => { const W = document.querySelector('.wrap').__rs.world(); const B = W.ball; B.p.x = 0; B.p.y = 4300; B.p.z = 300; B.v.x = 0; B.v.y = 2500; B.v.z = 0; W.lastTouch = W.cars[0]; W.touchHist.push({ c: W.cars[0], t: W.time, shot: false }); })()`);
  await p.waitForTimeout(700);
  await shot('06_goal');
  await p.waitForTimeout(1500);
  await shot('07_goal2');
  await p.waitForTimeout(2500);
  await shot('08_replay');
  const s2 = await p.evaluate(() => { const W = document.querySelector('.wrap').__rs.world(); return { score: W.score, state: W.state, t: W.stateT }; });
  log.push(JSON.stringify(s2));
  await p.waitForFunction(() => document.querySelector('.wrap').__rs.world().state !== 'goal', null, { timeout: 180000 }).catch(() => errs.push('stuck in goal state'));
  await p.waitForTimeout(800);
  await shot('09_after');
  await p.keyboard.down('Tab'); await p.waitForTimeout(400); await shot('10_tab'); await p.keyboard.up('Tab');
  await ev(`(() => { const W = document.querySelector('.wrap').__rs.world(); W.clock = 1; W.score = [3, 1]; })()`);
  await p.waitForFunction(() => document.querySelector('.wrap').__rs.world().state === 'end', null, { timeout: 180000 }).catch(() => errs.push('never ended'));
  await p.waitForTimeout(3500);
  await shot('11_end');
  console.log(log.join('\n'));
  console.log(errs.length ? errs.join('\n') : 'no errors');
  await b.close();
})();
